/** Normaliza para comparação: minúsculas, sem acento, espaços colapsados. */
export function normalizeSymptomName(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim()
}

export const SYMPTOM_CATALOG: SymptomEntry[] = (Object.keys(ITEMS) as SymptomGroupId[]).flatMap(
  (group) => ITEMS[group].map((name) => ({ name, group })),
)

const GROUP_BY_NAME = new Map(
  SYMPTOM_CATALOG.map((e) => [normalizeSymptomName(e.name), e.group] as const),
)

const GROUP_META = new Map(SYMPTOM_GROUPS.map((g) => [g.id, g] as const))

/** Grupo de um sintoma pelo nome; personalizados caem em "Geral". */
export function symptomGroupOf(name: string): SymptomGroup {
  const id = GROUP_BY_NAME.get(normalizeSymptomName(name)) ?? 'geral'
  return GROUP_META.get(id) as SymptomGroup
}
